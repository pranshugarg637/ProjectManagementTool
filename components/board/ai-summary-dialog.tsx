"use client";

import { useState } from "react";
import ReactMarkdown from "react-markdown";
import { RefreshCwIcon, SparklesIcon } from "lucide-react";
import { useBoard } from "@/components/board/board-context";
import { Button } from "@/components/ui/button";
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogHeader,
  DialogTitle,
  DialogTrigger,
} from "@/components/ui/dialog";
import { Skeleton } from "@/components/ui/skeleton";

type SummaryResponse = { summary?: string; error?: string; retryAfter?: number };

/** "AI Summary" button + dialog. Calls POST /api/boards/[id]/summary. */
export function AiSummaryDialog() {
  const { state } = useBoard();
  const [open, setOpen] = useState(false);
  const [loading, setLoading] = useState(false);
  const [summary, setSummary] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [generatedAt, setGeneratedAt] = useState<Date | null>(null);

  async function generate() {
    setLoading(true);
    setError(null);
    try {
      const res = await fetch(`/api/boards/${state.board.id}/summary`, { method: "POST" });
      const body = (await res.json()) as SummaryResponse;
      if (!res.ok || !body.summary) {
        setError(body.error ?? "Couldn't generate a summary.");
      } else {
        setSummary(body.summary);
        setGeneratedAt(new Date());
      }
    } catch {
      setError("Network error — please try again.");
    } finally {
      setLoading(false);
    }
  }

  return (
    <Dialog
      open={open}
      onOpenChange={(next) => {
        setOpen(next);
        if (next && !summary && !loading) void generate();
      }}
    >
      <DialogTrigger asChild>
        <Button variant="outline" size="sm">
          <SparklesIcon className="text-primary" /> AI Summary
        </Button>
      </DialogTrigger>
      <DialogContent className="sm:max-w-xl">
        <DialogHeader>
          <DialogTitle className="flex items-center gap-2">
            <SparklesIcon className="text-primary size-5" /> Board summary
          </DialogTitle>
          <DialogDescription>
            Generated by Google Gemini from the lists, cards, labels and due dates on this board.
          </DialogDescription>
        </DialogHeader>

        <div className="bg-muted/30 min-h-40 rounded-lg border p-4 text-sm">
          {loading ? (
            <div className="space-y-3" aria-label="Generating summary">
              <Skeleton className="h-4 w-1/3" />
              <Skeleton className="h-3 w-full" />
              <Skeleton className="h-3 w-5/6" />
              <Skeleton className="mt-4 h-4 w-1/4" />
              <Skeleton className="h-3 w-2/3" />
              <Skeleton className="h-3 w-3/4" />
            </div>
          ) : error ? (
            <p role="alert" className="text-muted-foreground">
              {error}
            </p>
          ) : summary ? (
            <div className="prose-summary">
              <ReactMarkdown>{summary}</ReactMarkdown>
            </div>
          ) : null}
        </div>

        <div className="text-muted-foreground flex items-center justify-between gap-2 text-xs">
          <span>
            {generatedAt
              ? `Generated at ${generatedAt.toLocaleTimeString()}`
              : "Limited to 1 request per board every 30 s."}
          </span>
          <Button variant="ghost" size="sm" onClick={() => void generate()} disabled={loading}>
            <RefreshCwIcon className={loading ? "animate-spin" : undefined} /> Regenerate
          </Button>
        </div>
      </DialogContent>
    </Dialog>
  );
}
